import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {chromium} from 'playwright-core';

const port=18787;
const server=spawn('node',['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port',String(port),'--strictPort'],{stdio:'ignore'});
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let browser;
try {
 let ready=false;
 for(let i=0;i<100;i++){try{ready=(await fetch(`http://127.0.0.1:${port}/`)).ok}catch{}if(ready)break;await wait(100)}
 assert.ok(ready,'Vite did not start');
 browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'block'});
 await context.addInitScript(()=>localStorage.setItem('gdp-works',JSON.stringify({'123':{hasText:true,pages:[1,2,3].map(position=>({position,imageId:String(position)}))}})));
 const page=await context.newPage(),errors=[];
 page.on('pageerror',error=>errors.push(String(error)));
 let releaseSecond;
 const second=new Promise(resolve=>{releaseSecond=resolve});
 const svg='<svg xmlns="http://www.w3.org/2000/svg" width="600" height="900"><rect width="600" height="900" fill="white"/></svg>';
 await page.route('https://biblioteca.galiciana.gal/**',async route=>{
  const id=new URL(route.request().url()).searchParams.get('idImagen');
  if(id==='2')await second;
  await route.fulfill({status:200,contentType:'image/svg+xml',body:svg}).catch(()=>{});
 });
 await page.goto(`http://127.0.0.1:${port}/?captura#screen=viewer&path=123&page=1&imageId=1&title=Prueba`);
 const view=page.locator('.viewer-viewport');
 await page.waitForFunction(()=>document.querySelector('.facsimile img.ready'));
 const cdp=await context.newCDPSession(page);
 const touch=async(type,x,y)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:type==='touchEnd'?[]:[{x,y,id:1}]});
 await touch('touchStart',310,400);
 await touch('touchMove',210,400);
 await page.waitForTimeout(50);
 const offset=await view.evaluate(el=>new DOMMatrixReadOnly(getComputedStyle(el).transform).m41);
 assert.ok(Math.abs(offset+100)<3,`page did not follow finger: ${offset}`);
 await touch('touchMove',130,400);
 await touch('touchEnd',130,400);
 await page.waitForFunction(()=>new URLSearchParams(location.hash.slice(1)).get('page')==='2',{},{timeout:1000});
 assert.equal(await page.locator('.page-skeleton').count(),1,'slow page must display loading state');
 await page.getByRole('button',{name:/Seguinte|Siguiente/}).click();
 await page.waitForFunction(()=>new URLSearchParams(location.hash.slice(1)).get('page')==='3',{},{timeout:1000});
 releaseSecond();
 await page.waitForTimeout(200);
 assert.equal(new URLSearchParams(new URL(page.url()).hash.slice(1)).get('page'),'3','late image changed the current page');
 await page.waitForFunction(()=>document.querySelector('.facsimile img.ready')?.getAttribute('src')?.includes('idImagen=3'));
 await page.waitForTimeout(400);
 await touch('touchStart',100,400);
 await touch('touchMove',150,400);
 await page.waitForTimeout(150);
 await touch('touchEnd',150,400);
 await page.waitForTimeout(30);
 await touch('touchStart',150,400);
 const beforeCatch=await view.evaluate(el=>new DOMMatrixReadOnly(getComputedStyle(el).transform).m41);
 await touch('touchMove',162,400);
 const afterCatch=await view.evaluate(el=>new DOMMatrixReadOnly(getComputedStyle(el).transform).m41);
 assert.ok(afterCatch>beforeCatch-5&&afterCatch<beforeCatch+16,`catch jumped: ${beforeCatch} -> ${afterCatch}`);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
 await page.waitForTimeout(500);
 assert.equal(new URLSearchParams(new URL(page.url()).hash.slice(1)).get('page'),'3','cancelled swipe changed page');
 assert.ok(Math.abs(await view.evaluate(el=>new DOMMatrixReadOnly(getComputedStyle(el).transform).m41))<1,'cancelled swipe did not settle');
 await page.getByRole('button',{name:/Accións desta páxina|Acciones de esta página/}).click();
 const sheet=page.locator('.m3-sheet');
 await sheet.waitFor();
 await page.waitForTimeout(600);
 const button=sheet.locator('.destination').first(),box=await button.boundingBox();
 assert.ok(box);
 await touch('touchStart',box.x+box.width/2,box.y+10);
 await touch('touchMove',box.x+box.width/2,box.y+70);
 assert.ok(Math.abs(await sheet.evaluate(el=>new DOMMatrixReadOnly(getComputedStyle(el).transform).m42))<1,'drag on a button moved the sheet');
 await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
 assert.deepEqual(errors,[]);
 await context.close();
 const reduced=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'block',reducedMotion:'reduce'});
 await reduced.addInitScript(()=>localStorage.setItem('gdp-works',JSON.stringify({'123':{hasText:true,pages:[1,2].map(position=>({position,imageId:String(position)}))}})));
 const reducedPage=await reduced.newPage();
 let fail=true;
 await reducedPage.route('https://biblioteca.galiciana.gal/**',route=>{
  const id=new URL(route.request().url()).searchParams.get('idImagen');
  return id==='2'&&fail?route.fulfill({status:503,body:'unavailable'}):route.fulfill({status:200,contentType:'image/svg+xml',body:svg});
 });
 await reducedPage.route('**/api/image?**',route=>route.fulfill({status:503,body:'unavailable'}));
 await reducedPage.goto(`http://127.0.0.1:${port}/?captura#screen=viewer&path=123&page=1&imageId=1&title=Prueba`);
 await reducedPage.waitForFunction(()=>document.querySelector('.facsimile img.ready'));
 const reducedCdp=await reduced.newCDPSession(reducedPage);
 await reducedCdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:310,y:400,id:1}]});
 await reducedCdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:130,y:400,id:1}]});
 await reducedCdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 await reducedPage.waitForFunction(()=>new URLSearchParams(location.hash.slice(1)).get('page')==='2');
 assert.equal(await reducedPage.locator('.viewer-viewport').evaluate(el=>el.getAnimations().length),0,'reduced motion animated the page turn');
 await reducedPage.getByText(/Non se puido abrir a páxina|No se pudo abrir la página/).waitFor();
 fail=false;
 await reducedPage.getByRole('button',{name:'Reintentar'}).click();
 await reducedPage.waitForFunction(()=>document.querySelector('.facsimile img.ready')?.getAttribute('src')?.includes('idImagen=2'));
 await reduced.close();
 console.log('Viewer touch tracking, slow loading and rapid navigation passed');
} finally {
 await browser?.close();
 server.kill('SIGTERM');
}
